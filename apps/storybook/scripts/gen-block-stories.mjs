#!/usr/bin/env node
/**
 * Storybook only renders WebKit's blocks; it never owns them. This writes one CSF file per block
 * from packages/webkit/blocks/<id>/block.json: every state renders the real `.vue` file and shows
 * its source, under the same title and export names the hand-written stories used (so links and
 * visual baselines keep their ids).
 *
 *   node apps/storybook/scripts/gen-block-stories.mjs           write
 *   node apps/storybook/scripts/gen-block-stories.mjs --check   fail when a file is stale (CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BLOCKS = resolve(APP, '../../packages/webkit/blocks')
const EXAMPLES = resolve(APP, '../../packages/webkit/examples')
const OUT = join(APP, 'src/stories/blocks')
const SITE_OUT = join(APP, 'src/stories/site')
const HEADER =
  '// Generated by apps/storybook/scripts/gen-block-stories.mjs — edit the block, not this file.\n'

function blockDirs(root, out = []) {
  for (const e of readdirSync(root, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name)
  )) {
    if (!e.isDirectory()) continue
    const dir = join(root, e.name)
    if (existsSync(join(dir, 'block.json'))) out.push(dir)
    else blockDirs(dir, out)
  }
  return out
}

const js = (v) => JSON.stringify(v)

export function storyFile(block, importBase) {
  const states = [
    { name: block.primary.name, summary: '', file: block.primary.file },
    ...(block.variants || [])
  ]
  const lines = [HEADER]
  states.forEach((s, i) => {
    lines.push(`import State${i} from '${importBase}/${s.file}'`)
    lines.push(`import source${i} from '${importBase}/${s.file}?raw'`)
  })
  const preview = block.preview || {}
  lines.push(
    '',
    'export default {',
    `  title: ${js(block.title)},`,
    "  tags: ['autodocs'],",
    '  parameters: {',
    `    layout: ${js(preview.layout || 'fullscreen')},`,
    ...(preview.background ? [`    backgrounds: { default: ${js(preview.background)} },`] : []),
    `    docs: { canvas: { sourceState: 'shown' }, description: { component: ${js(block.summary || '')} } },`,
    `    webkit: ${js({ block: block.id, intents: block.intents || [], skills: block.skills || [], ...(block.steps ? { steps: block.steps } : {}), primary: block.primary.name })}`,
    '  }',
    '}',
    ''
  )
  states.forEach((s, i) => {
    const own = s.preview || {}
    const layout =
      own.layout && own.layout !== (preview.layout || 'fullscreen')
        ? `layout: ${js(own.layout)}, `
        : ''
    const bg =
      own.background && own.background !== preview.background
        ? `backgrounds: { default: ${js(own.background)} }, `
        : ''
    lines.push(
      `export const ${s.name} = {`,
      `  render: () => ({ components: { Block: State${i} }, template: '<Block />' }),`,
      `  parameters: { ${layout}${bg}docs: { description: { story: ${js(s.summary || '')} }, source: { code: source${i} } } }`,
      '}',
      ''
    )
  })
  return lines.join('\n')
}

const kebab = (s) =>
  String(s)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

/** Marketing-site examples: each page section renders its `site-*.vue`, and its `*Json` story shows the page-JSON entry. */
export function siteFiles(manifest, sub, target) {
  const base = relative(dirname(target), join(EXAMPLES, sub)).split('\\').join('/')
  const lines = [HEADER]
  const stories = manifest.siteStories || []
  stories.forEach((name, i) => {
    const json = name.endsWith('Json')
    const file = `site-${kebab(json ? name.slice(0, -4) : name)}.${json ? 'json' : 'vue'}`
    if (!json) lines.push(`import State${i} from '${base}/${file}'`)
    lines.push(`import source${i} from '${base}/${file}?raw'`)
  })
  const preview = manifest.sitePreview || {}
  lines.push(
    '',
    'export default {',
    `  title: ${js(manifest.siteTitle)},`,
    '  parameters: {',
    `    layout: ${js(preview.layout || 'fullscreen')},`,
    ...(preview.background ? [`    backgrounds: { default: ${js(preview.background)} },`] : []),
    "    docs: { canvas: { sourceState: 'shown' } }",
    '  }',
    '}',
    ''
  )
  const summaries = Object.fromEntries((manifest.site || []).map((e) => [e.name, e.summary || '']))
  stories.forEach((name, i) => {
    if (name.endsWith('Json')) {
      lines.push(
        `export const ${name} = {`,
        "  tags: ['!dev'],",
        "  render: () => ({ template: '<div />' }),",
        `  parameters: { docs: { source: { code: source${i}, language: 'json' } } }`,
        '}',
        ''
      )
    } else {
      lines.push(
        `export const ${name} = {`,
        `  render: () => ({ components: { Section: State${i} }, template: '<Section />' }),`,
        `  parameters: { docs: { description: { story: ${js(summaries[name] || '')} }, source: { code: source${i} } } }`,
        '}',
        ''
      )
    }
  })
  const story = lines.join('\n')
  const readme = join(EXAMPLES, sub, 'README.md')
  const mdx = existsSync(readme)
    ? [
        "import { Markdown, Meta, Stories } from '@storybook/blocks'",
        '',
        `import * as SiteStories from './${sub}.stories'`,
        `import readme from '${base}/README.md?raw'`,
        '',
        '<Meta of={SiteStories} name="Documentation" />',
        '',
        '<Markdown>{readme}</Markdown>',
        '',
        '<Stories includePrimary />',
        ''
      ].join('\n')
    : null
  return { story, mdx }
}

export function generate() {
  const files = {}
  for (const sub of existsSync(EXAMPLES) ? readdirSync(EXAMPLES).sort() : []) {
    const mp = join(EXAMPLES, sub, 'examples.json')
    if (!existsSync(mp)) continue
    const manifest = JSON.parse(readFileSync(mp, 'utf8'))
    if (!manifest.siteTitle) continue
    const target = join(SITE_OUT, `${sub}.stories.js`)
    const { story, mdx } = siteFiles(manifest, sub, target)
    files[target] = story
    if (mdx)
      files[join(SITE_OUT, `${sub}.mdx`)] =
        HEADER.replace('// ', '{/* ').replace(/\n$/, ' */}\n') + mdx
  }
  for (const dir of blockDirs(BLOCKS)) {
    const block = JSON.parse(readFileSync(join(dir, 'block.json'), 'utf8'))
    const target = join(OUT, `${block.id}.stories.js`)
    const importBase = relative(dirname(target), dir).split('\\').join('/')
    files[target] = storyFile(block, importBase)
  }
  return files
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  const files = generate()
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files)
      .filter(([f, c]) => !existsSync(f) || readFileSync(f, 'utf8') !== c)
      .map(([f]) => relative(APP, f))
    if (stale.length) {
      process.stderr.write(`✗ stale block stories (run gen-block-stories): ${stale.join(', ')}\n`)
      process.exit(1)
    }
    process.stdout.write(`✓ ${Object.keys(files).length} block stories are current\n`)
  } else {
    rmSync(OUT, { recursive: true, force: true })
    rmSync(SITE_OUT, { recursive: true, force: true })
    for (const [f, c] of Object.entries(files)) {
      mkdirSync(dirname(f), { recursive: true })
      writeFileSync(f, c)
    }
    process.stdout.write(
      `${Object.keys(files).length} generated story files (blocks and site sections)\n`
    )
  }
}
