const COLUMNS = 160
const LON_ORIGIN = -157.11
const LON_PER_COLUMN = 2.1266
const ROW_AT_EQUATOR = 57.08
const ROWS_PER_MILLER = -33.913

const latitudeOf = (row: number) =>
  2.5 * (Math.atan(Math.exp((row - ROW_AT_EQUATOR) / ROWS_PER_MILLER / 1.25)) - Math.PI / 4)

/** Every land cell as a [longitude, latitude] pair, in radians. */
export const WORLD_LAND: ReadonlyArray<readonly [number, number]> = ROWS.flatMap((hex, row) =>
  BigInt(`0x${hex}`)
    .toString(2)
    .padStart(COLUMNS, '0')
    .split('')
    .flatMap((bit, column) =>
      bit === '1'
        ? [[((LON_ORIGIN + column * LON_PER_COLUMN) * Math.PI) / 180, latitudeOf(row)] as const]
        : []
    )
)
