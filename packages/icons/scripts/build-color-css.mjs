import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

import { COLOR_BASE, COLOR_DIR, glyphName, loadManifest } from './lib/icons-manifest.mjs'

const CHARSET = 'utf-8'
const DIST_DIR = './dist'

const INK_LIGHT = '#141414'
const INK_DARK = '#FAFAFA'

const DARK_SELECTORS = ['[data-theme=dark]', '.dark']
const DARK_SCOPE = `:is(${DARK_SELECTORS.join(', ')})`

mkdirSync(DIST_DIR, { recursive: true })

function svgToDataUri(svg) {
  const cleaned = svg
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .replace(/> </g, '><')
    .replace(/"/g, "'")
    .trim()

  const encoded = cleaned
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/{/g, '%7B')
    .replace(/}/g, '%7D')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')

  return `data:image/svg+xml,${encoded}`
}

const files = loadManifest()
  .icons.filter((entry) => entry.set === 'color')
  .map((entry) => `${glyphName(entry)}.svg`)

const sharedSelector = COLOR_BASE
const sharedRule = `@layer components {
  .${sharedSelector} {
    display: inline-block;
  }
}

.${sharedSelector} {
  width: 1em;
  height: 1em;
  background-repeat: no-repeat;
  background-position: center;
  background-size: contain;
  vertical-align: -0.125em;
}`

const withInk = (svg, ink) => svg.replace(/currentColor/gi, ink)

const paint = (selector, svg) =>
  `${selector} {\n  background-image: url("${svgToDataUri(svg)}");\n}`

let inkIcons = 0

const icons = files.map((file) => {
  const name = file.replace('.svg', '')
  const svg = readFileSync(join(COLOR_DIR, file), CHARSET)
  const inked = /currentColor/i.test(svg)
  if (inked) inkIcons += 1
  return {
    name,
    light: inked ? withInk(svg, INK_LIGHT) : svg,
    dark: inked ? withInk(svg, INK_DARK) : null
  }
})

const perIconRules = icons
  .map(({ name, light, dark }) => {
    const base = `.${sharedSelector}.${name}`
    if (!dark) return paint(base, light)
    const darkSelector = DARK_SELECTORS.map((scope) => `${scope} ${base}`).join(',\n')
    return `${paint(base, light)}\n\n${paint(darkSelector, dark)}`
  })
  .join('\n\n')

const indent = (text) => text.replace(/^/gm, '  ')

const perIconUtilities = icons
  .map(({ name, light, dark }) => {
    const rules = [paint(`&.${sharedSelector}`, light)]
    if (dark) rules.push(paint(`${DARK_SCOPE} &.${sharedSelector}`, dark))
    return `@utility ${name} {\n${indent(rules.join('\n'))}\n}`
  })
  .join('\n\n')

const css = `/* azionicons-color — every colored brand icon as background-image.
 * These are multicolor logos that cannot live in the woff2 font; use them like a
 * font icon, with the az-color base class instead of az: <i class="az-color az-google"></i>. Sizes with font-size (1em).
 * This file paints all ${files.length} logos. A Tailwind v4 app imports azionicons-color-utilities.css
 * instead (WebKit's styles do), so its stylesheet holds only the logos its sources name.
 * An icon whose SVG uses currentColor for its ink parts is emitted twice — light ink
 * in the base rule, dark ink under the theme's dark selectors — because a
 * background-image cannot inherit color from the element painting it.
 * Generated by scripts/build-color-css.mjs — do not edit by hand. */

${sharedRule}

${perIconRules}
`

const utilities = `/* azionicons-color utilities — the colored brand icons as Tailwind v4 utilities.
 * Import it in the stylesheet Tailwind compiles: Tailwind emits a logo's rule only when
 * a scanned source names its class (az-color az-google), so an app pays only for the
 * logos it uses. A logo named only in runtime data (fetched JSON) is not scanned: add
 * it with @source inline("az-google"), or import azionicons-color.css for every logo.
 * Generated by scripts/build-color-css.mjs — do not edit by hand. */

${sharedRule}

${perIconUtilities}
`

writeFileSync(join(DIST_DIR, 'azionicons-color.css'), css, CHARSET)
writeFileSync(join(DIST_DIR, 'azionicons-color-utilities.css'), utilities, CHARSET)

console.log(
  `  ✔ dist/azionicons-color.css and dist/azionicons-color-utilities.css created (${files.length} colored icons, ${inkIcons} theme-aware)`
)
