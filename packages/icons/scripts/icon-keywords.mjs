function bareName(name) {
  return name.replace(/^(ai|pi)-/, '')
}

export function iconKeywords(name) {
  const bare = bareName(name)
  const words = bare.split('-').filter(Boolean)
  const found = new Set(words.length > 1 ? words.filter((w) => w.length > 2) : [])
  const phrases = new Set([bare])
  for (let size = 2; size <= words.length; size++) {
    for (let i = 0; i + size <= words.length; i++) phrases.add(words.slice(i, i + size).join('-'))
  }
  for (const phrase of [...phrases, ...words]) {
    for (const keyword of WORD_KEYWORDS[phrase] ?? []) found.add(keyword)
  }
  if (words.some((w) => BRANDS.has(w))) found.add('brand').add('logo')
  found.delete(bare)
  return [...found]
}

export function iconKeywordString(name) {
  return iconKeywords(name).join(', ')
}
