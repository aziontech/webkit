import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

export const SOURCES_FILE = 'src/azion-ui.sources.css'
export const SOURCES_IMPORT = "@import './azion-ui.sources.css';"
export const SOURCE_EXCLUSIONS = ['../.claude', '../CLAUDE.md', '../AGENTS.md']
export const exclusionLine = (path) => `@source not '${path}';`

const escapeRe = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export function missingExclusions(css) {
  return SOURCE_EXCLUSIONS.filter(
    (path) => !new RegExp(`@source\\s+not\\s+['"]${escapeRe(path)}['"]`).test(css)
  )
}

const SOURCES_HEADER =
  '/* Generated by @aziontech/ui (the Vite plugin or `npx @aziontech/ui css`) from the Azion UI imports in this app. Do not edit. */'

const PKG_NAME = '@aziontech/ui'
const SCANNED_DIRS = ['components', 'composables', 'utils', 'assets', 'svg']
const CODE = /\.(vue|[cm]?[jt]sx?)$/
const SKIP_DIRS = new Set(['node_modules', 'dist', 'coverage', 'public', 'build', 'out'])
const SPECIFIER = /(?:\bfrom|\bimport)\s*\(?\s*['"]([^'"\n]+)['"]/g
const RESOLVE_SUFFIXES = ['', '.vue', '.ts', '.js', '.mjs', '/index.ts', '/index.js']

const toPosix = (p) => p.split(sep).join('/')

const isFile = (p) => {
  try {
    return statSync(p).isFile()
  } catch {
    return false
  }
}

const readText = (p) => {
  try {
    return readFileSync(p, 'utf8')
  } catch {
    return ''
  }
}

export function specifiersIn(text) {
  const out = []
  for (const m of text.matchAll(SPECIFIER)) out.push(m[1].split('?')[0])
  return out
}

export function azionUiSubpaths(text) {
  return specifiersIn(text)
    .filter((s) => s.startsWith(`${PKG_NAME}/`))
    .map((s) => s.slice(PKG_NAME.length + 1))
}

export function isAppSource(projectDir, file) {
  if (!CODE.test(file)) return false
  const rel = relative(projectDir, file)
  if (!rel || rel.startsWith('..')) return false
  return !rel.split(sep).some((seg) => SKIP_DIRS.has(seg) || seg.startsWith('.'))
}

export function appSourceFiles(projectDir) {
  const out = []
  const walk = (dir) => {
    let entries
    try {
      entries = readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      if (entry.name.startsWith('.') || SKIP_DIRS.has(entry.name)) continue
      const path = join(dir, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (entry.isFile() && CODE.test(entry.name)) out.push(path)
    }
  }
  walk(projectDir)
  return out.sort()
}

function findAzionUiDir(projectDir) {
  let dir = resolve(projectDir)
  for (;;) {
    const candidate = join(dir, 'node_modules', '@aziontech', 'ui')
    if (isFile(join(candidate, 'package.json'))) return candidate
    const parent = dirname(dir)
    if (parent === dir) return null
    dir = parent
  }
}

function exportTargetOf(entry) {
  if (typeof entry === 'string') return entry
  if (entry && typeof entry === 'object') return entry.default ?? entry.import ?? ''
  return ''
}

function azionUiClosure(azionUiDir, subpaths) {
  const pkg = JSON.parse(readFileSync(join(azionUiDir, 'package.json'), 'utf8'))
  const exportsMap = pkg.exports ?? {}
  const roots = SCANNED_DIRS.map((d) => join(azionUiDir, 'src', d) + sep)
  const seen = new Set()
  const queue = []
  const add = (file) => {
    if (!file || seen.has(file) || !CODE.test(file)) return
    if (!roots.some((root) => file.startsWith(root))) return
    seen.add(file)
    queue.push(file)
  }
  const fromExport = (sub) => {
    const target = exportTargetOf(exportsMap[`./${sub}`])
    return target ? join(azionUiDir, target) : null
  }
  const fromRelative = (base, spec) => {
    for (const suffix of RESOLVE_SUFFIXES) {
      const candidate = join(base, `${spec}${suffix}`)
      if (isFile(candidate)) return candidate
    }
    return null
  }
  for (const sub of subpaths) add(fromExport(sub))
  while (queue.length) {
    const file = queue.pop()
    for (const spec of specifiersIn(readText(file))) {
      if (spec.startsWith('.')) add(fromRelative(dirname(file), spec))
      else if (spec.startsWith(`${PKG_NAME}/`)) add(fromExport(spec.slice(PKG_NAME.length + 1)))
    }
  }
  return [...seen].sort()
}

function renderSources(cssDir, files) {
  const lines = files.map((file) => `@source "${toPosix(relative(cssDir, file))}";`)
  return `${[SOURCES_HEADER, ...lines].join('\n')}\n`
}

export function planSources(projectDir, opts = {}) {
  const file = opts.file ?? SOURCES_FILE
  const path = resolve(projectDir, file)
  const subpaths = new Set(
    opts.subpaths ?? appSourceFiles(projectDir).flatMap((f) => azionUiSubpaths(readText(f)))
  )
  const azionUiDir = opts.azionUiDir ?? findAzionUiDir(projectDir)
  const files = azionUiDir ? azionUiClosure(azionUiDir, [...subpaths].sort()) : []
  const content = renderSources(dirname(path), files)
  const current = existsSync(path) ? readText(path) : null
  return {
    file,
    path,
    content,
    current,
    stale: current !== content,
    resolved: Boolean(azionUiDir),
    subpaths: [...subpaths].sort(),
    files
  }
}

export function writeSources(plan) {
  if (!plan.stale) return false
  mkdirSync(dirname(plan.path), { recursive: true })
  writeFileSync(plan.path, plan.content, 'utf8')
  return true
}
