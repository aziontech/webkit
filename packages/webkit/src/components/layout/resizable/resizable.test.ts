import { fireEvent, render } from '@testing-library/vue'
import { describe, expect, it } from 'vitest'
import { h, nextTick, ref } from 'vue'

import { expectNoA11yViolations } from '../../../test/axe'
import Resizable, { ResizableHandle, ResizablePane } from './index'

// A composition root renders nothing on its own, so every case here composes a realistic
// group: one flexible pane, a handle, one sized pane. That is also the shape the handle's
// "which pane do I move" rule is written against, so a bare-root test would prove nothing
// about the only interesting behaviour this component has.
const group = (
  paneProps: Record<string, unknown> = {},
  handleProps: Record<string, unknown> = {}
) =>
  h(Resizable, null, {
    default: () => [
      h(ResizablePane, null, { default: () => 'document' }),
      h(ResizableHandle, { 'aria-label': 'Resize the preview', ...handleProps }),
      h(
        ResizablePane,
        { basis: 300, min: 200, max: 600, ...paneProps },
        { default: () => 'preview' }
      )
    ]
  })

describe('Resizable', () => {
  it('renders and exposes the fallback data-testid', () => {
    const { getByTestId } = render(group())
    expect(getByTestId('resizable')).toBeTruthy()
  })

  it('lets a consumer override data-testid', () => {
    const { getByTestId } = render(h(Resizable, { 'data-testid': 'custom-testid' }))
    expect(getByTestId('custom-testid')).toBeTruthy()
  })

  // The one place dot-notation is the subject rather than the vehicle: the parts the group
  // above renders are the same objects the root exposes, so `<Resizable.Pane>` in a
  // consumer's template resolves to what this file exercises. Read through `?.` because the
  // root's default export is generated by the SFC compiler — static analysis sees no
  // `export default` in a `.vue`, reads the binding as undefined, and flags every unguarded
  // member access on it.
  it('attaches its sub-components to the root for dot notation', () => {
    expect(Resizable).toBeTruthy()
    expect(Resizable?.Pane).toBe(ResizablePane)
    expect(Resizable?.Handle).toBe(ResizableHandle)
  })

  it('sizes the pane that has a basis and lets the other one absorb the rest', () => {
    const { getAllByTestId } = render(group())
    const [flexible, sized] = getAllByTestId('resizable-pane')
    expect(flexible.dataset.flexible).toBe('true')
    expect(sized.dataset.flexible).toBeUndefined()
    expect(sized.style.width).toBe('300px')
  })

  it('shrinks a sized pane before the flexible one drops under its minimum on a narrow group', () => {
    const { getAllByTestId } = render(
      h(
        Resizable,
        { style: 'display: flex; width: 240px' },
        {
          default: () => [
            h(ResizablePane, { min: 120 }, { default: () => 'source' }),
            h(ResizablePane, { basis: 320, min: 160 }, { default: () => 'preview' })
          ]
        }
      )
    )
    const [flexible, sized] = getAllByTestId('resizable-pane')
    expect(flexible.offsetWidth).toBe(120)
    expect(sized.offsetWidth).toBe(120)
    expect(sized.style.width).toBe('320px')
  })

  it('publishes the adjacent pane bounds on the separator', async () => {
    const { getByRole } = render(group())
    // The pane AFTER the handle registers in its own `mounted`, one tick later than the
    // handle rendered — so the bounds land on the next flush, never in the first frame.
    await nextTick()
    const handle = getByRole('separator')
    // A separator between side-by-side panes is itself VERTICAL.
    expect(handle.getAttribute('aria-orientation')).toBe('vertical')
    expect(handle.getAttribute('aria-valuenow')).toBe('300')
    expect(handle.getAttribute('aria-valuemin')).toBe('200')
    expect(handle.getAttribute('aria-valuemax')).toBe('600')
  })

  it('flips the separator orientation with the group axis', () => {
    const { getByRole } = render(
      h(
        Resizable,
        { orientation: 'vertical' },
        {
          default: () => [
            h(ResizablePane, null, { default: () => 'editor' }),
            h(ResizableHandle, { 'aria-label': 'Resize the terminal' }),
            h(ResizablePane, { basis: 176 }, { default: () => 'terminal' })
          ]
        }
      )
    )
    expect(getByRole('separator').getAttribute('aria-orientation')).toBe('horizontal')
  })

  it('renders a collapsed pane at zero length without unmounting its content', () => {
    const { getAllByTestId, getByText } = render(group({ open: false, collapsible: true }))
    const sized = getAllByTestId('resizable-pane')[1]
    expect(sized.dataset.state).toBe('closed')
    expect(sized.style.width).toBe('0px')
    // Still in the DOM — the whole point of collapsing rather than v-if.
    expect(getByText('preview')).toBeTruthy()
  })

  it('marks the separator disabled without removing it', () => {
    const { getByRole } = render(group({}, { disabled: true }))
    expect(getByRole('separator').getAttribute('aria-disabled')).toBe('true')
  })

  it('draws the focus ring token on the separator, not only a fill', () => {
    const { getByRole } = render(group())
    const classes = getByRole('separator').classList
    expect(classes.contains('focus-visible:ring-2')).toBe(true)
    expect(classes.contains('focus-visible:ring-(--ring-color)')).toBe(true)
  })

  it('has no axe violations on the default render', async () => {
    const { container } = render(group())
    await expectNoA11yViolations(container)
  })

  describe('keyboard and models', () => {
    const setup = async (paneProps: Record<string, unknown> = {}, dir = 'ltr') => {
      const basis: number[] = []
      const opens: boolean[] = []
      const size = ref(300)
      const view = render({
        render: () =>
          h('div', { dir }, [
            group({
              basis: size.value,
              'onUpdate:basis': (value: number) => {
                size.value = value
                basis.push(value)
              },
              'onUpdate:open': (value: boolean) => opens.push(value),
              ...paneProps
            })
          ])
      })
      await nextTick()
      return { ...view, handle: view.getByRole('separator'), basis, opens }
    }

    it('ArrowLeft grows the pane after the handle and ArrowRight shrinks it (ltr)', async () => {
      const { handle, basis } = await setup()
      await fireEvent.keyDown(handle, { key: 'ArrowLeft' })
      expect(basis.at(-1)).toBe(324)
      await nextTick()
      expect(handle.getAttribute('aria-valuenow')).toBe('324')
      await fireEvent.keyDown(handle, { key: 'ArrowRight' })
      expect(basis.at(-1)).toBe(300)
    })

    it('mirrors the arrows under rtl', async () => {
      const { handle, basis } = await setup({}, 'rtl')
      await fireEvent.keyDown(handle, { key: 'ArrowRight' })
      expect(basis.at(-1)).toBe(324)
      await fireEvent.keyDown(handle, { key: 'ArrowLeft' })
      expect(basis.at(-1)).toBe(300)
    })

    it('Home and End jump to the pane bounds', async () => {
      const { handle, basis } = await setup()
      await fireEvent.keyDown(handle, { key: 'Home' })
      expect(basis.at(-1)).toBe(200)
      await nextTick()
      expect(handle.getAttribute('aria-valuenow')).toBe('200')
      await fireEvent.keyDown(handle, { key: 'End' })
      expect(basis.at(-1)).toBe(600)
      await nextTick()
      expect(handle.getAttribute('aria-valuenow')).toBe('600')
    })

    it('Enter collapses a collapsible pane and restores it, emitting update:open', async () => {
      const { handle, opens, getAllByTestId } = await setup({ collapsible: true })
      const pane = getAllByTestId('resizable-pane')[1]
      await fireEvent.keyDown(handle, { key: 'Enter' })
      expect(opens.at(-1)).toBe(false)
      expect(pane.dataset.state).toBe('closed')
      await fireEvent.keyDown(handle, { key: 'Enter' })
      expect(opens.at(-1)).toBe(true)
      expect(pane.dataset.state).toBe('open')
    })

    it('has no expanded model: only open drives the pane', async () => {
      const { getAllByTestId } = await setup({ expanded: false, collapsible: true })
      expect(getAllByTestId('resizable-pane')[1].dataset.state).toBe('open')
    })

    it('Enter does nothing on a pane that is not collapsible', async () => {
      const { handle, opens } = await setup()
      await fireEvent.keyDown(handle, { key: 'Enter' })
      expect(opens).toEqual([])
    })

    it('open false renders the pane collapsed, and a bound parent drives it back', async () => {
      const open = ref(false)
      const { getAllByTestId } = render({
        setup: () => () =>
          group({
            collapsible: true,
            open: open.value,
            'onUpdate:open': (value: boolean) => (open.value = value)
          })
      })
      const pane = getAllByTestId('resizable-pane')[1]
      expect(pane.dataset.state).toBe('closed')
      open.value = true
      await nextTick()
      expect(pane.dataset.state).toBe('open')
    })
  })

  describe('on devices', () => {
    it('clips the handle hit area at its own edge', () => {
      const { getByTestId } = render(group())

      expect(getByTestId('resizable').className).toContain(
        'data-[orientation=horizontal]:overflow-x-clip'
      )
    })
  })
})
